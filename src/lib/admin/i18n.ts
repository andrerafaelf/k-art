// Times are shown in Madeira time, wherever the browser or server is
const ZONE = 'Atlantic/Madeira';
const dayKey = (d: Date) => new Intl.DateTimeFormat('en-CA', { timeZone: ZONE }).format(d);

/** "today at 14:02", "yesterday at 09:15" or "on 8 October at 18:40" */
export function when(iso: string, m: AdminMessages, now = Date.now()) {
	const d = new Date(iso);
	const time = new Intl.DateTimeFormat(m.locale, { timeZone: ZONE, hour: '2-digit', minute: '2-digit' }).format(d);
	const key = dayKey(d);
	if (key === dayKey(new Date(now))) return m.time.today(time);
	if (key === dayKey(new Date(now - 86_400_000))) return m.time.yesterday(time);
	const sameYear = key.slice(0, 4) === dayKey(new Date(now)).slice(0, 4);
	const date = new Intl.DateTimeFormat(m.locale, {
		timeZone: ZONE,
		day: 'numeric',
		month: 'long',
		...(sameYear ? {} : { year: 'numeric' })
	}).format(d);
	return m.time.on(date, time);
}

/** Heading for a day in the history: "Today", "Yesterday" or "Wednesday, 8 October" */
export function dayHeading(iso: string, m: AdminMessages, now = Date.now()) {
	const d = new Date(iso);
	const key = dayKey(d);
	if (key === dayKey(new Date(now))) return m.time.dayToday;
	if (key === dayKey(new Date(now - 86_400_000))) return m.time.dayYesterday;
	const sameYear = key.slice(0, 4) === dayKey(new Date(now)).slice(0, 4);
	const text = new Intl.DateTimeFormat(m.locale, {
		timeZone: ZONE,
		weekday: 'long',
		day: 'numeric',
		month: 'long',
		...(sameYear ? {} : { year: 'numeric' })
	}).format(d);
	return text[0].toUpperCase() + text.slice(1);
}

export { dayKey };
